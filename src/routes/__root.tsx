function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="es-UY">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function FooterSwitch() {
  const { pathname } = useLocation();
  if (pathname.startsWith("/admin")) return null;
  return <SiteFooter />;
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        <CartProvider>
          <a href="#contenido" className="sr-only focus:not-sr-only focus:fixed focus:left-4 focus:top-4 focus:z-50 focus:rounded focus:bg-primary focus:px-3 focus:py-2 focus:text-primary-foreground">
            Saltar al contenido
          </a>
          <div className="flex min-h-screen flex-col">
            <SiteHeader />
            <main id="contenido" className="flex-1">
              {/* Required: nested routes render here. */}
              <Outlet />
            </main>
            <FooterSwitch />
          </div>
          <Toaster richColors position="top-right" />
        </CartProvider>
      </AuthProvider>
    </QueryClientProvider>
  );
}
